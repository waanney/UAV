"""Split-conformal compatibility scores for object detections.

This module calibrates detection confidence against a held-out set of matched
true positives. Its p-values measure compatibility with that calibration
distribution; they are not probabilities that a detection is correct.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np


class SplitConformalDetector:
    """Class-conditional split conformal scoring for detection confidence.

    Non-conformity is defined as ``1 - confidence``. Calibration examples
    should be detections matched to ground-truth objects using a fixed class
    and IoU matching rule. The model and inference settings must remain fixed
    between calibration and evaluation.

    Args:
        alpha: Significance level used by :meth:`accept`. An example is
            ``alpha=0.1`` for a 10% significance threshold.
        min_class_samples: Minimum number of matched calibration examples
            required before using a class-specific calibration distribution.
            Classes below this count use the global distribution instead.
    """

    FORMAT_VERSION = 1

    def __init__(self, alpha: float = 0.1, min_class_samples: int = 20) -> None:
        if not 0.0 < alpha < 1.0:
            raise ValueError(f"alpha must be in (0, 1), got {alpha}")
        if min_class_samples < 1:
            raise ValueError("min_class_samples must be at least 1")

        self.alpha = float(alpha)
        self.min_class_samples = int(min_class_samples)
        self.global_scores: np.ndarray | None = None
        self.class_scores: dict[int, np.ndarray] = {}

    @staticmethod
    def _as_1d(values: Any, name: str, dtype: Any) -> np.ndarray:
        array = np.asarray(values, dtype=dtype)
        if array.ndim != 1:
            raise ValueError(f"{name} must be one-dimensional, got shape {array.shape}")
        return array

    def fit(
        self,
        confidence: Any,
        is_true_positive: Any,
        class_ids: Any,
    ) -> "SplitConformalDetector":
        """Fit calibration distributions from matched detections.

        Args:
            confidence: Raw detector confidence values in ``[0, 1]``.
            is_true_positive: Boolean TP labels for each detection. These
                labels must be generated by matching predictions to ground
                truth on a calibration split, never on the test split.
            class_ids: Predicted class id for each detection.

        Returns:
            The fitted instance.

        Raises:
            ValueError: If inputs have different lengths, contain invalid
                confidence values, or no true-positive calibration examples.
        """
        confidence = self._as_1d(confidence, "confidence", float)
        is_true_positive = self._as_1d(is_true_positive, "is_true_positive", bool)
        class_ids = self._as_1d(class_ids, "class_ids", int)

        if not (len(confidence) == len(is_true_positive) == len(class_ids)):
            raise ValueError("confidence, is_true_positive, and class_ids must have equal lengths")
        if not np.all(np.isfinite(confidence)) or np.any((confidence < 0.0) | (confidence > 1.0)):
            raise ValueError("confidence values must be finite and in [0, 1]")

        tp_mask = is_true_positive
        if not np.any(tp_mask):
            raise ValueError("No true-positive calibration detections were provided")

        # Low confidence corresponds to higher non-conformity.
        self.global_scores = 1.0 - confidence[tp_mask]
        self.class_scores = {}
        for class_id in np.unique(class_ids[tp_mask]):
            class_mask = tp_mask & (class_ids == class_id)
            scores = 1.0 - confidence[class_mask]
            if len(scores) >= self.min_class_samples:
                self.class_scores[int(class_id)] = scores

        return self

    def _scores_for_class(self, class_id: int) -> np.ndarray:
        if self.global_scores is None:
            raise RuntimeError("Call fit() or load() before computing conformal scores")
        return self.class_scores.get(int(class_id), self.global_scores)

    def predict_p_value(self, confidence: Any, class_ids: Any) -> np.ndarray:
        """Compute add-one conformal p-values for candidate detections.

        A larger p-value means the candidate confidence is more compatible
        with the matched-TP calibration scores. It must not be interpreted as
        ``P(detection is correct)``.
        """
        confidence = self._as_1d(confidence, "confidence", float)
        class_ids = self._as_1d(class_ids, "class_ids", int)
        if len(confidence) != len(class_ids):
            raise ValueError("confidence and class_ids must have equal lengths")
        if not np.all(np.isfinite(confidence)) or np.any((confidence < 0.0) | (confidence > 1.0)):
            raise ValueError("confidence values must be finite and in [0, 1]")

        p_values = np.empty(len(confidence), dtype=float)
        for i, (conf, class_id) in enumerate(zip(confidence, class_ids)):
            calibration_scores = self._scores_for_class(int(class_id))
            candidate_score = 1.0 - conf
            # Count ties as at least as non-conforming for conservative ranks.
            p_values[i] = (1 + np.count_nonzero(calibration_scores >= candidate_score)) / (
                len(calibration_scores) + 1
            )
        return p_values

    def accept(self, p_values: Any) -> np.ndarray:
        """Return whether each candidate passes the configured alpha threshold."""
        p_values = self._as_1d(p_values, "p_values", float)
        if not np.all(np.isfinite(p_values)) or np.any((p_values < 0.0) | (p_values > 1.0)):
            raise ValueError("p_values must be finite and in [0, 1]")
        return p_values > self.alpha

    def save(self, path: str | Path) -> None:
        """Save fitted calibration scores and settings as JSON."""
        if self.global_scores is None:
            raise RuntimeError("Cannot save an unfitted conformal calibrator")

        payload = {
            "format_version": self.FORMAT_VERSION,
            "alpha": self.alpha,
            "min_class_samples": self.min_class_samples,
            "global_scores": self.global_scores.tolist(),
            "class_scores": {str(k): v.tolist() for k, v in self.class_scores.items()},
        }
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    @classmethod
    def load(cls, path: str | Path) -> "SplitConformalDetector":
        """Load a previously saved calibrator from JSON."""
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
        if payload.get("format_version") != cls.FORMAT_VERSION:
            raise ValueError(f"Unsupported conformal state format: {payload.get('format_version')}")

        calibrator = cls(
            alpha=float(payload["alpha"]),
            min_class_samples=int(payload["min_class_samples"]),
        )
        global_scores = np.asarray(payload["global_scores"], dtype=float)
        if global_scores.ndim != 1 or len(global_scores) == 0:
            raise ValueError("Saved global calibration scores must be a non-empty list")
        calibrator.global_scores = global_scores
        calibrator.class_scores = {
            int(k): np.asarray(v, dtype=float) for k, v in payload["class_scores"].items()
        }
        return calibrator

